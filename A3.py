First_band = str.lower(input("Enter the color of first band of resistor"))
if First_band == 'black':
    print("0")
elif First_band == 'brown':
    print("1")
elif First_band == 'red':
    print("2")
elif First_band == 'orange':
    print("3")
elif First_band == 'yellow':
    print("4")
elif First_band == 'green':
    print("5")
elif First_band == 'blue':
    print("6")
elif First_band == 'voilet':
    print("7")
elif First_band == 'grey':
    print("8")
elif First_band == 'white':
    print("9")
else :
    print("Invalid input")

